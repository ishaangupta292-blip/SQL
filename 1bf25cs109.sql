SELECT DISTINCT P.PNAME
FROM PARTS P
JOIN CATALOG C
ON P.PID = C.PID;
SELECT S.SNAME
FROM SUPPLIERS S
WHERE NOT EXISTS (
    SELECT *
    FROM PARTS P
    WHERE NOT EXISTS (
        SELECT *
        FROM CATALOG C
        WHERE C.SID = S.SID
        AND C.PID = P.PID
    )
);
SELECT S.SNAME
FROM SUPPLIERS S
WHERE NOT EXISTS (
    SELECT *
    FROM PARTS P
    WHERE P.COLOR = 'Red'
    AND NOT EXISTS (
        SELECT *
        FROM CATALOG C
        WHERE C.SID = S.SID
        AND C.PID = P.PID
    )
);
