SELECT DISTINCT C1.SID
FROM CATALOG C1
WHERE C1.COST > (
    SELECT AVG(C2.COST)
    FROM CATALOG C2
    WHERE C2.PID = C1.PID
);
SELECT P.PNAME, S.SNAME, C.COST
FROM CATALOG C
JOIN SUPPLIERS S
ON C.SID = S.SID
JOIN PARTS P
ON C.PID = P.PID
WHERE C.COST = (
    SELECT MAX(C2.COST)
    FROM CATALOG C2
    WHERE C2.PID = C.PID
);
